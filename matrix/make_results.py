#!/usr/bin/env python3
"""Results for the matrix Gross-Neveu-Yukawa models of Prakash and Sinha (arXiv:2307.06841): C_T and C_J through eps^3 at
their fixed points, the planar limit in closed form, and d = 3 estimates from pole-free Pade approximants of the 4 - eps
series (no d = 2 input).  Writes ../results/matrix_models.md.  (~20 s)"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import numpy as np
import sympy as sp

from ctcj.pade import all_pades
from fastseries import numeric
import largeN
from run_models import fixed_point, setup, FP3, fp_su_susy, fp_s2_susy, eps as meps
from ctcj.formulas4 import KAPPA_T_ODD, KAPPA_J_ODD, odd_invariant_T, odd_invariants_J, value
from formulas import CT3, CJ3, is_odd, evaluate


import functools
_setup = functools.lru_cache(maxsize=None)(setup)       # the SU(6) tensors take minutes; build each once


def odd_shift(key, kind="T", printed=False):
    """O(eps^3) odd fermion-loop term of C_T/C_T,free (these points have no four-dimensional counterpart):
    (7/6 - zeta3) Tr(y^a y^b y^c)Tr(y^a y^b y^c) / (n_s + 3/2 n_f), couplings at leading order; likewise for C_J.
    printed=False: from ctcj.formulas4; printed=True: from the last terms of ct3.tex, cj3.tex (the paper's formulas),
    which fixed_point() includes."""
    if key[:3] in ("SUN", "S2N"):
        model, N = key[:2], int(key[3:])
        Ys = (fp_su_susy if model == "SU" else fp_s2_susy)(sp.Integer(N))[0]
    else:
        model, N = ("SU" if key.startswith("SU") else ("S2" if "A2" not in key else "A2")), 3
        Ys = FP3[key][0]
    Y, L1, L2, T, t, nsc, nfe = _setup(model, N)
    y1 = float(sp.series(Ys, meps, 0, 2).removeO().coeff(meps, 1))
    if printed:
        terms = [x for x in (CT3 if kind == "T" else CJ3) if is_odd(x[2])]
        r, z = list(evaluate(terms, Y, {}, T, t).values())[0]
        free = nsc + 1.5 * nfe if kind == "T" else np.trace(T @ T).real + (t ** 2).sum() / 2
        return complex(r + z * value((0, 1))).real * y1 ** 3 / free
    if kind == "T":
        return value(KAPPA_T_ODD) * odd_invariant_T(Y) * y1 ** 3 / (nsc + 1.5 * nfe)
    I0, I1 = odd_invariants_J(Y, T)                          # C_J,free/C_J,psi = Tr(TT) + t.t/2
    return (value(KAPPA_J_ODD[0]) * I0 + value(KAPPA_J_ODD[1]) * I1) * y1 ** 3 / (np.trace(T @ T).real + (t ** 2).sum() / 2)

POINTS = [("SU3_susy", "SU(3) adjoint, [susy]"), ("SUN4", "SU(4) adjoint, [susy]"), ("SUN6", "SU(6) adjoint, [susy]"),
          ("S2N3", "SO(3) S^2, [susy]"), ("S2N4", "SO(4) S^2, [susy]"), ("S2N6", "SO(6) S^2, [susy]"),
          ("SO3S2A2_ns+", "SO(3) S^2-A^2, [ns+]")]

out = ["# Matrix Gross-Neveu-Yukawa models", "",
       "Generated by `matrix/make_results.py`.  Fixed points in the notation of Prakash and Sinha (arXiv:2307.06841).  C_J is for a",
       "generator of SU(N) or SO(N).  Entries are the coefficients of eps, eps^2, eps^3 in C/C_free - 1.  The d = 3 columns give the",
       "range of the pole-free Pade approximants [m,n], m + n = 3, of the 4 - eps series alone.  These points have no",
       "four-dimensional counterpart: C_T includes the odd fermion-loop term (7/6 - zeta3) Tr(y^a y^b y^c)Tr(y^a y^b y^c) at",
       "O(eps^3), fixed by N=1 supersymmetry (ODD_LOOPS.md), and C_J the corresponding -3 I0 + (2 - 6 zeta3) I1, confirmed by",
       "the N=1 flavour-current multiplet (scripts/supercurrent_jj.py).", "",
       "| fixed point | C_T: eps | eps^2 | eps^3 | C_J: eps | eps^2 | eps^3 | C_T, d = 3 | C_J, d = 3 |",
       "|---|---|---|---|---|---|---|---|---|"]


def rng(a):
    v = [x for _, x in all_pades(list(a), [])]
    return f"{min(v):.3f} – {max(v):.3f}" if v else "none pole-free"


for key, label in POINTS:
    ct, cj = fixed_point(key)
    a, b = numeric(ct), numeric(cj)
    for kind in ("T", "J"):        # the odd fermion loops are in the printed formulas; check them against ctcj.formulas4
        assert abs(odd_shift(key, kind, printed=True) - odd_shift(key, kind)) < 1e-10, (key, kind)
    out.append(f"| {label} | " + " | ".join(f"{x:+.5f}" for x in a[1:]) + " | " + " | ".join(f"{x:+.5f}" for x in b[1:])
               + f" | {rng(a)} | {rng(b)} |")

e, z = largeN.eps, largeN.z3
lT = [float(sp.N(largeN.CT.coeff(e, k).subs(z, sp.zeta(3)))) for k in range(4)]
# odd fermion loops survive the planar limit: at the SU(N) adjoint [susy] point the term is exactly
#   (7/6 - zeta3)/10240 x (N^2-12)^2 (N^2-4)/(4 N^3) x (16N/(5N^2-36))^3   (d_aij d_bjk d_cki = (N^2-12)/(2N) d_abc),
# checked against odd_shift at N = 3, 4, 6, 8, and -> (7/6 - zeta3)/1250 as N -> infinity.
def odd_su(N):
    return value(KAPPA_T_ODD) / 10240 * (N * N - 12) ** 2 * (N * N - 4) / (4 * N ** 3) * (16 * N / (5 * N * N - 36)) ** 3
for N in (4, 6):
    assert abs(odd_su(N) - odd_shift(f"SUN{N}")) < 1e-12 * abs(odd_su(N))
    paper = value(KAPPA_T_ODD) * (N * N - 4) * (N * N - 12) ** 2 / (10 * (5 * N * N - 36) ** 3)     # form quoted in the paper
    assert abs(paper - odd_su(N)) < 1e-12 * abs(paper)
# the same for C_J: at the SU(N) adjoint [susy] point the odd-loop term of C_J/C_J,free is exactly
#   (N^2-4)(3N^4 - 64N^2 + 48N^2 zeta3 - 288 zeta3 + 384) / (12 (5N^2-36)^3)    (exact group factors fitted on
# N = 3..14 to 1e-14, scripts/supercurrent_jj.py at N = 3), -> 1/500; the SO(N) S^2 [susy] family has the same limit.
def odd_su_J(N):
    zz = float(sp.zeta(3))
    return (N * N - 4) * (3 * N ** 4 - 64 * N ** 2 + 48 * N ** 2 * zz - 288 * zz + 384) / (12 * (5 * N * N - 36) ** 3)
for N in (4, 6):
    assert abs(odd_su_J(N) - odd_shift(f"SUN{N}", "J")) < 1e-12 * abs(odd_su_J(N))
lJ = [float(sp.N(largeN.CJ.coeff(e, k).subs(z, sp.zeta(3)))) for k in range(4)]
out.append("| large N (planar) | " + " | ".join(f"{x:+.5f}" for x in lT[1:]) + " | " + " | ".join(f"{x:+.5f}" for x in lJ[1:])
           + f" | {rng(lT)} | {rng(lJ)} |")
out += ["", "Planar limit, in closed form (exact in N before the limit, from the double-line expansion in `matrix/planar.py`):", "",
        f"- C_T/C_T,free = {largeN.CT}",
        f"- C_J/C_J,free = {largeN.CJ}", "",
        "These include the odd fermion loops, which survive the planar limit.  At the SU(N) adjoint [susy] point they contribute",
        "(7/6 - zeta3)(N^2-4)(N^2-12)^2/(10 (5N^2-36)^3) eps^3 to C_T/C_T,free (from d_aij d_bjk d_cki = (N^2-12)/(2N) d_abc) and",
        "(N^2-4)(3N^4 - 64N^2 + 384 + 48 zeta3 (N^2-6))/(12 (5N^2-36)^3) eps^3 to C_J/C_J,free (group factors fitted exactly on",
        "N = 3..14, checked here at N = 4, 6), which tend to (7/6 - zeta3)/1250 and 1/500; the SO(N) S^2 [susy] points have the same",
        "limits.  Without them (four-dimensional traces only):", "",
        f"- C_T/C_T,free = {largeN.CT_EVEN}", f"- C_J/C_J,free = {largeN.CJ_EVEN}", ""]

open(os.path.join(HERE, "..", "results", "matrix_models.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
