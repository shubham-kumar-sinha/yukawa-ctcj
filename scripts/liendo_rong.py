#!/usr/bin/env python3
"""C_T (and C_J where the symmetry is continuous) through O(eps^3) at N=1 supersymmetric fixed points of
Liendo and Rong (arXiv:2107.14515): super-Potts models (S_q acting on N_Phi = q - 1 real superfields) and the
O(3)/Z2 model (N_Phi = 5, superfields in symmetric traceless 3x3 matrices).

Each model is set up from its symmetry alone: N_Phi real scalars and N_Phi Majorana fermions (Tr 1 = 1 each) in
the same representation, with the general invariant Yukawa and quartic tensors (group averaging, or Lie-algebra
nullspace for O(3)).  The general fixed-point solver (ctcj.theory) finds the fixed points; supersymmetry is not
imposed.  Checks: gamma_Phi equals Liendo-Rong's table; the quartic equals its supersymmetric value
lambda_abcd = h_abe h_cde + 2 pairings at O(eps) and O(eps^2); q = 3 reproduces the N=2 super-Ising C_T.
Writes results/liendo_rong.md.  (~5 min)"""
import itertools, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np
from ctcj.theory import Theory
from ctcj.pade import all_pades

ROOT = os.path.join(os.path.dirname(__file__), "..")
rng = np.random.default_rng(11)


def span(tensors, tol=1e-9):
    A = np.array([t.ravel() for t in tensors])
    u, s, vt = np.linalg.svd(A, full_matrices=False)
    k = int((s > tol * s[0]).sum())
    return [vt[i].reshape(tensors[0].shape) for i in range(k)]


def sym4(t):
    return sum(np.transpose(t, p) for p in itertools.permutations(range(4))) / 24


def yuk_from_group(Rs, n, samples=6):
    out = []
    for _ in range(samples):
        y = rng.normal(size=(n, n, n)); y = y + y.transpose(0, 2, 1)
        out.append(sum(np.einsum("ab,bij,ki,lj->akl", R, y, R, R) for R in Rs) / len(Rs))
    return span(out)


def quart_from_group(Rs, n, samples=8):
    out = []
    for _ in range(samples):
        l = sym4(rng.normal(size=(n,) * 4))
        out.append(sum(np.einsum("ae,bf,cg,dh,efgh->abcd", R, R, R, R, l, optimize=True) for R in Rs) / len(Rs))
    return span(out)


def potts(q):
    n = q - 1
    V = np.linalg.qr(np.vstack([np.ones(q), np.eye(q)[:-1]]).T)[0][:, 1:]      # orthonormal, orthogonal to (1,..,1)
    Rs = [V.T @ np.eye(q)[list(p)] @ V for p in itertools.permutations(range(q))]
    return yuk_from_group(Rs, n), quart_from_group(Rs, n), None


def o3_traceless():
    E = []
    for i in range(3):
        for j in range(i, 3):
            M = np.zeros((3, 3)); M[i, j] = M[j, i] = 1
            E.append(M)
    E = np.array(E)
    B = []
    for M in E:                                             # traceless orthonormal basis
        M = M - np.trace(M) / 3 * np.eye(3)
        for P in B:
            M = M - np.trace(M @ P) * P
        if np.linalg.norm(M) > 1e-9:
            B.append(M / np.linalg.norm(M))
    B = np.array(B)                                         # 5 x 3 x 3
    gens = []
    for (i, j) in ((0, 1), (0, 2), (1, 2)):
        A = np.zeros((3, 3)); A[i, j], A[j, i] = 1, -1
        gens.append(np.einsum("aij,jk,bki->ab", B, A, B) - np.einsum("aij,bjk,ki->ab", B, B, A))   # D(A)_ab
    n = 5

    def null(rank, symfun):
        dim = n ** rank
        rows = []
        for G in gens:
            for k in range(dim):
                e = np.zeros(dim); e[k] = 1; T = e.reshape((n,) * rank)
                act = sum(np.moveaxis(np.tensordot(G, T, axes=([1], [i])), 0, i) for i in range(rank))
                rows.append(act.ravel())
        M = np.array(rows).T
        u, s, vt = np.linalg.svd(M.T)
        ns_ = vt[(s > 1e-9).sum():]
        return span([symfun(v.reshape((n,) * rank)) for v in ns_] or [np.zeros((n,) * rank)])
    Y = null(3, lambda t: t + t.transpose(0, 2, 1))
    L = null(4, sym4)
    return Y, L, gens


MODELS = [("super-Potts S3 (N_Phi=2)", potts(3), 1 / 6), ("super-Potts S4 (N_Phi=3)", potts(4), 1 / 10),
          ("super-Potts S5 (N_Phi=4)", potts(5), 3 / 34), ("O(3)/Z2 (N_Phi=5)", o3_traceless(), 7 / 30)]

out = ["# C_T and C_J at N=1 supersymmetric fixed points of Liendo and Rong (arXiv:2107.14515)", "",
       "Generated by `scripts/liendo_rong.py`.  Each theory is built from its symmetry alone (general invariant Yukawa and",
       "quartic tensors); supersymmetry is not imposed.  gamma_Phi: one-loop superfield anomalous dimension / eps.",
       "C_T includes the odd fermion-loop term (7/6 - zeta3) Tr(y^a y^b y^c)Tr(y^a y^b y^c) at O(eps^3) (zero at S3, which has a",
       "four-dimensional counterpart), fixed by N=1 supersymmetry (ODD_LOOPS.md); C_J likewise includes -3 I0 + (2 - 6 zeta3) I1,",
       "confirmed by the N=1 flavour-current multiplet (scripts/supercurrent_jj.py).", "",
       "| model | gamma_Phi (ours; Liendo-Rong) | SUSY quartic at O(eps), O(eps^2) | C_T/C_T,free = 1 + c1 eps + c2 eps^2 + c3 eps^3 | d = 3: series; pole-free Pade |",
       "|---|---|---|---|---|"]
extra = []
for name, (Ys, Ls, gens), gref in MODELS:
    th = Theory(Y=[np.array(y, complex) for y in Ys], L=Ls, mult=1.0, name=name)
    best = None
    for fp in th.fixed_points(starts=80):
        y1 = th.y_of(fp["a"])
        h = y1.real
        gam = 0.5 * np.einsum("aij,bji->ab", y1, y1).real
        g = gam[0, 0]
        if not np.allclose(gam, g * np.eye(len(gam)), atol=1e-8) or abs(g - gref) > 1e-6:
            continue
        lam_s = (np.einsum("abe,cde->abcd", h, h) + np.einsum("ace,bde->abcd", h, h) + np.einsum("ade,bce->abcd", h, h))
        if np.abs(th.lam_of(fp["c"]) - lam_s).max() < 1e-7:
            best = fp
            break
    assert best is not None, f"{name}: SUSY fixed point with gamma = {gref} not found"
    fp3 = th.third_order(best)
    y1, y2 = th.y_of(fp3["a"]).real, th.y_of(fp3["b"]).real
    P = lambda u, v: (np.einsum("abe,cde->abcd", u, v) + np.einsum("ace,bde->abcd", u, v) + np.einsum("ade,bce->abcd", u, v))
    l2_susy = P(y1, y2) + P(y2, y1)
    ok2 = np.abs(th.lam_of(fp3["e"]) - l2_susy).max() < 1e-7
    c = th._series(fp3, "T", odd=True)                     # 3d-only theories: odd fermion-loop term included
    vals = [v for _, v in all_pades(list(c), [])]
    out.append(f"| {name} | {g:.6f}; {gref:.6f} | yes (selected), {'yes' if ok2 else 'NO'} | "
               f"1 {c[1]:+.6f} eps {c[2]:+.6f} eps^2 {c[3]:+.6f} eps^3 | {sum(c):.4f}; {min(vals):.4f} – {max(vals):.4f} |")
    print(out[-1], flush=True)
    if gens is not None:                                     # continuous symmetry: C_J for one O(3) generator
        A = gens[0]
        for sgn in (1, -1):
            T, t = 1j * A, sgn * A
            if th.check_current(T, t, best):
                cj = th._series(fp3, "J", (T, t), odd=True)        # odd fermion-loop term included
                vj = [v for _, v in all_pades(list(cj), [])]
                extra.append(f"- {name}, O(3) current: C_J/C_J,free = 1 {cj[1]:+.6f} eps {cj[2]:+.6f} eps^2 {cj[3]:+.6f} eps^3;  "
                             f"d = 3: series {sum(cj):.4f}, pole-free Pade {min(vj):.4f} – {max(vj):.4f}")
                print(extra[-1], flush=True)
                break
out += [""] + extra + ["", "Check: the S3 super-Potts point is the N=2 super-Ising model; its C_T must equal "
        "1 - eps/6 - eps^2/8 + (zeta3/12 - 73/864) eps^3 = 1 - 0.166667 eps - 0.125 eps^2 + 0.015681 eps^3.", ""]
open(os.path.join(ROOT, "results", "liendo_rong.md"), "w").write("\n".join(out) + "\n")
