#!/usr/bin/env python3
"""Estimates of C_T and C_J in d = 3 for the chiral GNY fixed points, from our O(eps^3) results in d = 4 - eps
combined (where available) with exact d = 2 data or the 2 + eps expansions of Diab et al. (arXiv:1601.07198).

Two-sided Pade approximants R = P(eps)/Q(eps) in eps = 4 - d match the 4 - eps series through eps^K and the d = 2
information (a value, or a series in d - 2 through order L); every [m, n] with m + n + 1 = (K + 1) + (L + 1) is
tried and only approximants without poles for 2 <= d <= 4 are kept.  Their spread is a rough uncertainty.
Writes results/pade_3d.md.  (~2 min)"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np
import sympy as sp
from ctcj.eps3models import series, eps
from ctcj.pade import pade, all_pades

ROOT = os.path.join(os.path.dirname(__file__), "..")
out = ["# C_T and C_J in d = 3 from the eps-expansion", "",
       "Generated by `scripts/pade3d.py`.  4 - eps input: this work, through eps^3.  Pade approximants listed only if pole-free",
       "for 2 <= d <= 4.  'value' = approximant at d = 3.", ""]


def coeffs(s, K):
    return [float(sp.N(s.coeff(eps, k), 30)) for k in range(K + 1)]


def table(title, rows, ref=None):
    out.extend([f"### {title}", "", "| input | pole-free Pade approximants at d = 3 | range |", "|---|---|---|"])
    for lab, res in rows:
        vals = [v for _, v in res]
        rng = f"{min(vals):.4f} – {max(vals):.4f}" if vals else "none pole-free"
        out.append(f"| {lab} | " + ", ".join(f"{k} {v:.4f}" for k, v in res) + f" | {rng} |")
    if ref:
        out.append(""); out.append(ref)
    out.append("")


# ---------------------------------------------------------------- N=2 SUSY point (chiral XY, N = 2)
sT = series("chiral XY", 2, "T")
out += ["## Supersymmetric points (exact d = 2 endpoints)", "",
        f"N=2 (chiral XY, N=2): C_T/C_T,free = C_J^R/C_J^R,free = {sp.nsimplify(sT)}", ""]
exact = 256 / 243 - 16 / (9 * np.sqrt(3) * np.pi)
a3 = coeffs(sT, 3)
table("N=2 super-Ising (3d N=2 Wess-Zumino): C_T/C_T,free", [
    ("eps^2 + d=2 value 1/3", all_pades(a3[:3], [1 / 3])),
    ("eps^3 + d=2 value 1/3", all_pades(a3, [1 / 3])),
    ("eps^3 only", all_pades(a3, [])),
], ref=f"Exact (localization): 256/243 - 16/(9 sqrt3 pi) = {exact:.4f}.  FGKT (arXiv:1607.05316), Pade[1,1] with O(eps) input: 0.77.  Truncated series at eps=1: "
       f"O(eps^2) {sum(a3[:3]):.4f}, O(eps^3) {sum(a3):.4f}.  d = 2: N=2 minimal model, c = 1 vs 3 free.")
# ---------------------------------------------------------------- N=1 SUSY point (chiral Ising, N = 1)
s1 = series("chiral Ising", 1, "T", odd=True)          # 3d-only: odd fermion-loop term included
a1 = coeffs(s1, 3)
out += [f"N=1 (chiral Ising, N=1): C_T/C_T,free = {sp.nsimplify(s1)}", "", "C_T at this 3d-only point includes the odd fermion-loop term (7/6 - zeta3) Tr(y^a y^b y^c)Tr(y^a y^b y^c) at O(eps^3), fixed by N=1 supersymmetry (ODD_LOOPS.md).", ""]
table("N=1 super-Ising: C_T/C_T,free", [
    ("eps^2 + d=2 value 7/15", all_pades(a1[:3], [7 / 15])),
    ("eps^3 + d=2 value 7/15", all_pades(a1, [7 / 15])),
    ("eps^3 only", all_pades(a1, [])),
], ref=f"Truncated series at eps=1: O(eps^2) {sum(a1[:3]):.4f}, O(eps^3) {sum(a1):.4f}.  d = 2: tricritical Ising, c = 7/10 vs 3/2 free.  "
       "Bootstrap: C_T/C_T,free = 1.68414(14)/2 = 0.84207(7) (Atanasov et al., arXiv:2201.02206; earlier estimate 1.684/2, Rong and Su, arXiv:1807.04434).  FGKT, Pade[1,1] with O(eps) input: 0.86.")

# ---------------------------------------------------------------- Gross-Neveu, N = 4, 8
out += ["## Gross-Neveu-Yukawa (chiral Ising), with the 2 + eps Gross-Neveu expansions of Diab et al.", "",
        "N = Tr 1 = number of 3d Majorana fermions (N = 8: graphene CDW transition).  C_T is normalised to the free",
        "fermions only, as in Diab et al.; the Pade is done on f(d) = C_T/(C_T,ferm + C_T,scalar) - 1 (their eq. for f),", ""]
for N in (4, 8):
    sJ, sTn = series("chiral Ising", N, "J"), series("chiral Ising", N, "T")
    aJ = coeffs(sJ, 3)
    bJ = [1.0, -1 / (N - 2), -1 / (2 * (N - 2) ** 2)]
    aF = coeffs(sp.expand(sTn - 1), 3)          # f(4 - eps) = our ratio - 1
    bF = [-2 / (N + 2), 2 * N / (N + 2) ** 2, -2 * N ** 2 / (N + 2) ** 3,
          (15 * N ** 5 - 69 * N ** 4 + 58 * N ** 3 + 4 * N ** 2 + 8 * N) / (8 * (N - 2) ** 2 * (N + 2) ** 4)]
    conv = 1 + 1 / N                             # C_T/C_T,ferm = (1 + f)(1 + 2/(N(d-1))) at d = 3
    resF = [(k, (1 + v) * conv) for k, v in all_pades(aF, bF)]
    resF2 = [(k, (1 + v) * conv) for k, v in all_pades(aF[:2], bF)]
    table(f"GN N={N}: C_J/C_J,free", [("eps^1 + (2+eps)^2 [Diab et al. input]", all_pades(aJ[:2], bJ)),
                                       ("eps^3 + (2+eps)^2", all_pades(aJ, bJ))],
          ref=f"Large N: 1 - 64/(9 pi^2 N) = {1 - 64 / (9 * np.pi ** 2 * N):.4f}.  Diab et al. Pade[2,2] (eps^1 input): "
              f"{ {4: 0.7931, 8: 0.9016}[N] }.")
    table(f"GN N={N}: C_T/C_T,ferm", [("eps^1 + (2+eps)^3 [Diab et al. input]", resF2), ("eps^3 + (2+eps)^3", resF)],
          ref=f"Large N: 1 + 8/(9 pi^2 N) = {1 + 8 / (9 * np.pi ** 2 * N):.4f}.  Diab et al. (average of [1,4],[4,1], eps^1 input): "
              f"{ {4: 1.0147, 8: 1.0107}[N] }.")

# ---------------------------------------------------------------- validation at large N
out += ["### Validation of the procedure at large N", "",
        "The same two-sided Pade (eps^3 + Diab et al. 2+eps) at large N must reproduce the exact 1/N coefficients in d = 3,",
        "N(C_J/C_J,free - 1) -> -64/(9 pi^2) = -0.7205 and N(C_T/C_T,ferm - 1) -> 8/(9 pi^2) = 0.0901.", "",
        "| N | N(C_J - 1), pole-free Pade | N(C_T - 1), pole-free Pade |", "|---|---|---|"]
for N in (8, 20, 100, 400):
    sJ, sTn = series("chiral Ising", N, "J"), series("chiral Ising", N, "T")
    aJ = coeffs(sJ, 3); bJ = [1.0, -1 / (N - 2), -1 / (2 * (N - 2) ** 2)]
    aF = coeffs(sp.expand(sTn - 1), 3)
    bF = [-2 / (N + 2), 2 * N / (N + 2) ** 2, -2 * N ** 2 / (N + 2) ** 3,
          (15 * N ** 5 - 69 * N ** 4 + 58 * N ** 3 + 4 * N ** 2 + 8 * N) / (8 * (N - 2) ** 2 * (N + 2) ** 4)]
    vJ = [N * (v - 1) for _, v in all_pades(aJ, bJ)]
    vT = [N * ((1 + v) * (1 + 1 / N) - 1) for _, v in all_pades(aF, bF)]
    out.append(f"| {N} | {min(vJ):.3f} – {max(vJ):.3f} | {min(vT):.3f} – {max(vT):.3f} |")
out += ["", "The C_T values follow N(C_T/C_T,ferm - 1) ~ 0.090 + 0.69/N, so the larger C_T at small N is a 1/N^2 effect.", ""]

# ---------------------------------------------------------------- chiral XY C_T, two-sided with d = 2 value
out += ["## Chiral XY (NJLY): C_T with the d = 2 endpoint", "",
        "At d = 2 the fixed point merges with free fermions, so C_T/C_T,ferm = 1 there (only the value is used).  Pade on",
        "f = C_T/(C_T,ferm + 2 C_T,scalar) - 1, with f(d=2) = -4/(N+4).  Large N (FGKT, arXiv:1607.05316): 1 + 16/(9 pi^2 N) in d = 3.", ""]
for N in (4, 8):
    aF = coeffs(sp.expand(series("chiral XY", N, "T") - 1), 3)
    conv = 1 + 2 / N                               # C_T/C_T,ferm = (1 + f)(1 + 4/(N(d-1))) at d = 3
    resF = [(k, (1 + v) * conv) for k, v in all_pades(aF, [-4 / (N + 4)])]
    table(f"chiral XY N={N}: C_T/C_T,ferm", [("eps^3 + d=2 value", resF)],
          ref=f"Large N: 1 + 16/(9 pi^2 N) = {1 + 16 / (9 * np.pi ** 2 * N):.4f}.")

# ---------------------------------------------------------------- chiral XY and Heisenberg (one-sided)
out += ["## Chiral XY and chiral Heisenberg (4 - eps only)", "",
        "No 2 + eps expansions of C_T or C_J are known to us for these models (for C_T of chiral XY see the two-sided Pade above); listed are the truncated series at eps = 1 and pole-free one-sided Pade.", ""]
for model, Ns in (("chiral XY", (4, 8)), ("chiral Heisenberg", (4, 8))):
    for N in Ns:
        for kind in ("T", "J"):
            s = series(model, N, kind)
            a = coeffs(s, 3)
            out.append(f"- {model} N={N}, C_{kind}/C_{kind},free = 1 {a[1]:+.5f} eps {a[2]:+.5f} eps^2 {a[3]:+.5f} eps^3;  "
                       f"truncated at eps=1: {sum(a[:3]):.4f} (eps^2), {sum(a):.4f} (eps^3);  "
                       + "Pade " + ", ".join(f"{k} {v:.4f}" for k, v in all_pades(a, [])))
out.append("")
open(os.path.join(ROOT, "results", "pade_3d.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
