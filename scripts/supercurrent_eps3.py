#!/usr/bin/env python3
"""C_S/C_S,free through O(eps^3) at the N=1 super-Ising point (one Majorana,
y = h, lambda = l), and the odd-trace coefficient kappa_T it implies.

    python3 scripts/supercurrent_compute.py --w 0 2 4 --proj P             (through three loops)
    python3 scripts/supercurrent_compute.py --w 6 --fast --depth 3 --proj P (222 four-loop classes, ~15 min)
    python3 scripts/supercurrent_eps3.py            (~1 min; writes results/supercurrent_ising.md)

For one field every class is h^nY l^nQ times a number, so the renormalisation is done symbolically in (h, l):
    h0 = mu^ep (h + b1/eps + b2/(2 eps) + D2/eps^2),  D2 = 1/2 Db1[b1],   l0 = mu^(2 ep) (l + bl1/eps),  eps = 2 ep
(JOS conventions, couplings rescaled by 4 pi as in ctcj/assemble4.py; the mu factors are in position_ratio).
<S Sbar> has no odd-trace contributions through O(eps^3) (scripts/count_supercurrent_odd.py), so the 4d-algebra
result is complete.  If C_S/C_S,free = C_T/C_T,free, then
    kappa_T Tr(yyy)^2 (C_T,S/C_T,free) = [C_S/C_S,free - C_T^(4d)/C_T,free]_(eps^3),
with Tr(yyy)^2 = eps^3 a^6 at leading order and C_T,free/C_T,S = 1 + 3/2 Tr 1 = 5/2.
"""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np
import sympy as sp
from ctcj import epsseries as S
from ctcj.assemble import position_ratio
from ctcj.supercurrent import generate_S, generate_S_fast, flavour
from ctcj.theory import Theory
from ctcj import betasJ as BJ

ROOT = os.path.join(os.path.dirname(__file__), "..")
e = S.EP
cache = json.load(open(os.path.join(ROOT, "data", "supercurrent_classes.json")))
SYM = {"ep": e, **{f"z{k}": sp.Symbol(f"z{k}") for k in range(2, 8)}}
h, l, t, eps = sp.symbols("h l t eps")
one, one4 = np.ones((1, 1, 1)), np.ones((1, 1, 1, 1))


def Xsum(classes):
    """sum over classes of (flavour number at h = l = 1) x X, grouped by monomial h^nY l^nQ"""
    out = {}
    for c in classes:
        key = (c["nY"], c["nQ"])
        x = sp.sympify(cache[f"{c['name']}|P"]["X"], locals=SYM)
        out[key] = sp.expand(out.get(key, 0) + sp.Rational(round(flavour(c, one, one4) * 1e6), 10 ** 6) * x)
    return out


XF = sp.sympify(cache[f"{generate_S(0, 0)[0]['name']}|P"]["X"], locals=SYM)
THREE = "--three" in sys.argv                     # test mode: stop at three loops (eps^3 results meaningless)
C4 = [c for nY, nQ in [(6, 0), (4, 1), (2, 2), (0, 3)] for c in generate_S_fast(nY, nQ, reps=True)]
missing = [c["name"] for c in C4 if f"{c['name']}|P" not in cache]
assert THREE or not missing, f"{len(missing)} four-loop classes not computed yet"
loops = {2: Xsum(generate_S(2, 0)),
         3: Xsum(generate_S(4, 0) + generate_S(2, 1) + generate_S(0, 2)),
         4: {} if THREE else Xsum(C4)}

# ------------------------------------------------------------------ beta functions for one field, as polynomials
def fit(fun, monos):
    pts = [(1.3, 0.7), (0.6, 1.9), (1.1, -0.4), (2.0, 0.5), (0.8, 1.2), (1.7, -1.1)]
    A = np.array([[float(m.subs({h: a, l: b})) for m in monos] for a, b in pts])
    v = np.array([fun(a, b) for a, b in pts])
    sol = np.linalg.lstsq(A, v, rcond=None)[0]
    assert np.allclose(A @ sol, v)
    return sum(sp.nsimplify(round(s, 10), rational=True) * m for s, m in zip(sol, monos))


Y = lambda a: np.array([[[a]]], complex)
L = lambda b: np.full((1, 1, 1, 1), b)
b1 = fit(lambda a, b: BJ.beta1_y(Y(a), 1.0)[0, 0, 0].real, [h ** 3])
b2 = fit(lambda a, b: BJ.beta2_y(Y(a), L(b), 1.0)[0, 0, 0].real, [h ** 5, h ** 3 * l, h * l ** 2])
bl1 = fit(lambda a, b: BJ.beta1_lam(Y(a), L(b), 1.0)[0, 0, 0, 0].real, [l ** 2, l * h ** 2, h ** 4])
D2 = sp.expand(sp.diff(b1, h) * b1 / 2)
OUT = ["# The N=1 supercurrent at the super-Ising point through O(eps^3): the odd-loop coefficient kappa_T", "",
       "Generated by `scripts/supercurrent_eps3.py` from the integrals cached in `data/supercurrent_classes.json`; see",
       "ODD_LOOPS.md.  Paper: section 5.4 and appendix F.  One superfield: y = h, lambda = l (couplings rescaled as in JOS).", ""]


def say(line=""):
    print(line, flush=True)
    OUT.append(line)


say(f"One-loop and two-loop beta functions: beta1_y = {b1},  beta2_y = {b2},  beta1_lambda = {bl1}.")
say("")

h0 = h + b1 / (2 * e) + b2 / (4 * e) + D2 / (4 * e ** 2)
l0 = l + bl1 / (2 * e)

# ------------------------------------------------------------------ renormalised position-space ratio
total = 0
for L_, terms in loops.items():
    for (nY, nQ), X in terms.items():
        R = position_ratio("S", L_, X, XF)
        g = {h: t * h, l: t * t * l}                  # grading: h ~ t, l ~ t^2
        mono = sp.expand(h0.subs(g, simultaneous=True) ** nY * l0.subs(g, simultaneous=True) ** nQ)
        mono = sp.expand(sp.series(mono, t, 0, 7).removeO())
        total += sp.expand(mono * R)
total = sp.expand(total)
ren = {k: sp.expand(total.coeff(t, k)) for k in ((2, 4) if THREE else (2, 4, 6))}
say("## Poles of the renormalised C_S/C_S,free (ep = (4-d)/2)")
say("")
say("| order | 1/ep^2 | 1/ep | on the supersymmetric line l = 3h^2 |")
say("|---|---|---|---|")
ok_poles = True
for k, v in ren.items():
    v = S.trunc(v, 2)
    poles = [sp.factor(sp.expand(v.coeff(e, j))) for j in (-4, -3, -2, -1)]
    ok_poles &= poles[0] == 0 and poles[1] == 0
    on = all(sp.simplify(p.subs(l, 3 * h ** 2)) == 0 for p in poles)
    ok_poles &= on
    say(f"| h^{k} | {poles[2]} | {poles[3]} | {'vanish' if on else '**do not vanish**'} |")
say("")

# ------------------------------------------------------------------ super-Ising fixed point
th = Theory(Y=[one.astype(complex)], L=[one4], mult=1.0, name="super-Ising")
fp = next(f for f in th.fixed_points(starts=80)
          if abs(th.y_of(f["a"])[0, 0, 0]) > 1e-6 and abs(th.lam_of(f["c"])[0, 0, 0, 0] - 3 * th.y_of(f["a"])[0, 0, 0].real ** 2) < 1e-8)
fp3 = th.third_order(fp)
A = [sp.Float(th.y_of(fp3[k])[0, 0, 0].real, 20) for k in ("a", "b", "d")]
C = [sp.Float(th.lam_of(fp3[k])[0, 0, 0, 0], 20) for k in ("c", "e")]
if A[0] < 0:                                       # y -> -y symmetry: pick y* > 0 (C_S, C_T even in y)
    A = [-a for a in A]
hs = A[0] + A[1] * eps + A[2] * eps ** 2          # y* / sqrt(eps)
ls = C[0] + C[1] * eps                             # lambda* / eps
CS = 1
for k, v in ren.items():
    v = sp.expand(S.trunc(v, 3).subs(e, eps / 2))
    v = sp.expand(v.subs({h: hs, l: ls}) * eps ** (k // 2))      # weight k: eps^(k/2) x polynomial in (hs, ls)
    CS += v
CS = sp.expand(sp.series(sp.expand(CS), eps, 0, 4).removeO())
NUM = {S.GAMMA_E: 0.5772156649015329, S.LOGPI: float(np.log(np.pi)), S.LOG4: float(np.log(4)),
       **{sp.Symbol(f"z{k}"): float(sp.zeta(k)) for k in range(2, 8)}}
cS, ok_logs = [], True
for j in range(4):
    cj = sp.expand(CS.coeff(eps, j))
    logs = [float(sp.N(sp.diff(cj, s).subs(NUM).subs(S.ELL, 0.3))) for s in (S.ELL, S.GAMMA_E, S.LOGPI)]
    ok_logs &= max(abs(x) for x in logs) < 1e-12
    cS.append(float(sp.N(sp.expand(cj.subs({S.ELL: 0, S.GAMMA_E: 0, S.LOGPI: 0, S.LOG4: 0})).subs(NUM))))
cT = th.CT3(fp)
say("## Super-Ising fixed point")
say("")
say("| | eps | eps^2 | eps^3 |")
say("|---|---|---|---|")
say("| C_S/C_S,free | " + " | ".join(f"{x:+.10f}" for x in cS[1:]) + " |")
say("| C_T/C_T,free, four-dimensional traces | " + " | ".join(f"{x:+.10f}" for x in cT[1:]) + " |")
say("")
d3 = cS[3] - cT[3]
a6 = float(A[0]) ** 6
kappa = d3 * 2.5 / a6
z3 = float(sp.zeta(3))
ok_low = abs(cS[1] - cT[1]) < 1e-12 and abs(cS[2] - cT[2]) < 1e-12
say(f"No log(mu^2 x^2), gamma_E or log pi at any order: {'yes' if ok_logs else '**no**'}.  "
    f"Equal at O(eps) and O(eps^2): {'yes' if ok_low else '**no**'}.")
say("")
say(f"At O(eps^3), C_S/C_S,free - C_T/C_T,free (four-dimensional traces) = {d3:+.10f}.  With Tr(yyy)Tr(yyy) = eps^3/343 and")
say(f"C_T,free/C_T,S = 5/2 this requires Delta C_T/C_T,S = kappa_T Tr(yyy)Tr(yyy) with kappa_T = {kappa:+.8f}.  Candidates")
say("(ODD_LOOPS.md):")
say("")
say("| continuation of the five-gamma odd traces | kappa_T | agrees with C_S |")
say("|---|---|---|")
ok_kappa = False
for name, val in [("both traces read at T", 7 / 24 - z3 / 4), ("same-line rule, f = 1 (DREG_3)", 7 / 6 - z3),
                  ("same-line rule, Fierz into one even trace, f = (7-D)/4", 7 / 8 - 3 * z3 / 4),
                  ("inversion-tensor sewing", 0.0), ("one trace at T, one at the middle Yukawa vertex", 14 * (7 / 24 - z3 / 4))]:
    hit = abs(kappa - val) < 1e-10
    ok_kappa |= hit and name.startswith("same-line rule, f = 1")
    say(f"| {name} | {val:+.8f} | {'**yes**' if hit else 'no'} |")
say("")
ok_all = ok_poles and ok_logs and ok_low and ok_kappa
say(f"kappa_T = 7/6 - zeta3: {'PASS' if ok_kappa else 'FAIL'}")
if not THREE:
    open(os.path.join(ROOT, "results", "supercurrent_ising.md"), "w").write("\n".join(OUT) + "\n")
sys.exit(0 if ok_all else 1)
