#!/usr/bin/env python3
"""Tables and checks of the paper for the chiral Ising, XY and Heisenberg models that are not produced elsewhere:

  1. C_T and C_J through eps^3 for N = 1, 2, 4, 8 (the table of the chiral models);
  2. the N = 2 point of chiral XY: C_J of the U(1) current equals 9(d-2)/((d-1)(d+2)) times C_T/C_T,free, exactly
     through eps^3 (the U(1) current is three times the superconformal R-current only at the interacting point);
  3. the universal conductivity sigma/sigma_free = C_J/C_J,free of the fermion-number current, at N = 8 and N = 4,
     from pole-free two-sided Pade approximants with the free value at d = 2, and the large-N validation at N = 400;
  4. the exact conductivity at the supersymmetric semimetal-superconductor transition;
  5. the 1/N and 1/N^2 coefficients of C_T and C_J for the Gross-Neveu-Yukawa model, through eps^3.

Writes results/paper_tables.md.  The exit code is non-zero if a check fails.  (~2 min)"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np
import sympy as sp

from ctcj import gny3loop as G
from ctcj.eps3models import MODELS, S_tensor, _value, degrees, eps, load_coefficients, name_net, series
from ctcj.net import evaluate
from ctcj.pade import all_pades

ROOT = os.path.join(os.path.dirname(__file__), "..")
out = ["# Chiral GNY models: tables and checks", "",
       "Generated by `scripts/paper_tables.py`.  N = Tr 1 counts two-component Majorana fermions (graphene: N = 8).", ""]
failures = []


def check(name, ok):
    out.append(f"- {name}: **{'PASS' if ok else 'FAIL'}**")
    if not ok:
        failures.append(name)


def f4(c):
    """Four decimals, rounding halves away from zero (as in the paper's tables)."""
    from decimal import Decimal, ROUND_HALF_UP
    q = Decimal(repr(c)).quantize(Decimal("0.0001"), rounding=ROUND_HALF_UP)
    return f"{q:+.4f}"


def num(s, K=3):
    return [float(sp.N(s.coeff(eps, k), 20)) for k in range(K + 1)]


# ------------------------------------------------------------------ 1. chiral models through eps^3
out += ["## 1. C_T and C_J of the chiral models through eps^3", "",
        "Stable fixed point.  Currents: any fermion-only flavor current (Ising), the U(1) with fermion charge 1 and scalar charge 2 (XY),",
        "the SU(2) generator sigma_3/2 (Heisenberg).  Entries are the coefficients of eps, eps^2, eps^3 in C/C_free - 1.",
        "Chiral Ising at N = 1 (one Majorana fermion) and at N = 2 (one two-component Dirac fermion, with the U(1) whose C_J is given)",
        "have no four-dimensional counterpart; their C_T includes the odd fermion-loop term (7/6 - zeta3) Tr(y^a y^b y^c)Tr(y^a y^b y^c)",
        "at O(eps^3), fixed by N=1 supersymmetry (ODD_LOOPS.md).  Their C_J has no such term (Tr(Theta y^a y^b y^c) = 0).  N = 4, 8 are",
        "the theories obtained from four dimensions, without odd-loop terms.", "",
        "| model | N | C_T: eps | eps^2 | eps^3 | C_J: eps | eps^2 | eps^3 |", "|---|---|---|---|---|---|---|---|"]
for model in ("chiral Ising", "chiral XY", "chiral Heisenberg"):
    for N in (1, 2, 4, 8):
        # chiral Ising at N = 1 (one Majorana) and N = 2 (one two-component Dirac fermion with a U(1), the theory whose C_J the
        # row gives) have no four-dimensional counterpart; y = 1 with Tr 1 = N is their actual flavour structure, so the
        # odd-loop term applies.  N = 4, 8 are the graphene-type theories from four dimensions (Tr(yyy) = 0).
        cT = num(series(model, N, "T", odd=(model == "chiral Ising" and N in (1, 2))))
        row = f"| {model} | {N} | " + " | ".join(f4(c) for c in cT[1:])
        if model == "chiral Ising" and N == 1:
            row += " | --- | --- | --- |"
        else:
            cJ = num(series(model, N, "J"))
            row += " | " + " | ".join(f4(c) for c in cJ[1:]) + " |"
        out.append(row)
out.append("")

# ------------------------------------------------------------------ 2. N = 2 point: U(1) current vs R-current
d = 4 - eps
sT = series("chiral XY", 2, "T")
sJ = series("chiral XY", 2, "J")
factor = sp.series(9 * (d - 2) / ((d - 1) * (d + 2)), eps, 0, 4).removeO()
diff = sp.simplify(sp.expand(sp.series(sJ - factor * sT, eps, 0, 4).removeO()))
out += ["## 2. Chiral XY at N = 2 (N=2 super-Ising): the U(1) current and the R-current", "",
        f"C_T/C_T,free = {sp.nsimplify(sT)}", "",
        f"C_J/C_J,free (U(1) current, charges 1 and 2) = {sp.nsimplify(sJ)}", "",
        f"9(d-2)/((d-1)(d+2)) = {sp.nsimplify(factor)} + O(eps^4)", ""]
check("C_J/C_J,free = 9(d-2)/((d-1)(d+2)) C_T/C_T,free through eps^3 (exact)", diff == 0)
out.append("")

# ------------------------------------------------------------------ 3. conductivity of Dirac critical points
ns = {"chiral Ising": 1, "chiral XY": 2, "chiral Heisenberg": 3}


def number_current(model):
    n = MODELS[model][0].shape[1]
    return np.eye(n, dtype=complex), np.zeros((ns[model], ns[model]))


def sigma(model, N):
    s = series(model, N, "J", current=number_current(model))
    a = num(s)
    vals = [v for _, v in all_pades(a, [1.0])]
    return a, vals


out += ["## 3. Universal conductivity sigma/sigma_free = C_J/C_J,free of the fermion-number current", "",
        "Pole-free two-sided Pade approximants matching the eps^3 series and the free value 1 at d = 2.  For chiral Ising the",
        "approximants with the full 2 + eps input of Diab et al. are in `results/pade_3d.md`.  Large N: 1 - 64 n_s/(9 pi^2 N).", "",
        "| model (graphene order) | N=8: eps | eps^2 | eps^3 | N=8, d=3 Pade | large N | N=4, d=3 Pade | large N |",
        "|---|---|---|---|---|---|---|---|"]
names = {"chiral Ising": "CDW", "chiral XY": "Kekule", "chiral Heisenberg": "Neel"}
for model in ns:
    a8, v8 = sigma(model, 8)
    _, v4 = sigma(model, 4)
    lN = lambda N: 1 - 64 * ns[model] / (9 * np.pi**2 * N)
    out.append(f"| {model} ({names[model]}) | {f4(a8[1])} | {f4(a8[2])} | {f4(a8[3])} | {min(v8):.3f} – {max(v8):.3f} | {lN(8):.3f} "
               f"| {min(v4):.3f} – {max(v4):.3f} | {lN(4):.3f} |")
out += ["", "Validation at N = 400: N (C_J/C_J,free - 1) from the same approximants, against the exact large-N value -64 n_s/(9 pi^2).", "",
        "| model | Pade range | exact | max deviation |", "|---|---|---|---|"]
for model in ns:
    _, v = sigma(model, 400)
    v = [400 * (x - 1) for x in v]
    ex = -64 * ns[model] / (9 * np.pi**2)
    dev = max(abs(x / ex - 1) for x in v)
    out.append(f"| {model} | {min(v):.3f} – {max(v):.3f} | {ex:.3f} | {100 * dev:.0f}% |")
    check(f"{model}: N = 400 approximants bracket the exact large-N value, within 12%", min(v) <= ex <= max(v) and dev < 0.12)
out.append("")

# ------------------------------------------------------------------ 4. exact conductivity at the TI-surface transition
tau = sp.Rational(4, 243) * (16 - 9 * sp.sqrt(3) / sp.pi)       # tau_RR of the 3d N=2 Wess-Zumino model (localization)
ct = 4 * tau                                                       # C_T/C_T,free (free chiral: tau_RR = 1/4)
sig = sp.Rational(9, 10) * ct
out += ["## 4. Semimetal-superconductor transition on a topological-insulator surface (N=2 super-Ising)", "",
        f"C_T/C_T,free = 4 tau_RR = {sp.nsimplify(ct)} = {float(ct):.4f} (localization)", "",
        f"sigma/sigma_free = (9/10) C_T/C_T,free = {sp.simplify(sig)} = {float(sig):.4f}", "",
        f"sigma = (5/16) sigma/sigma_free e^2/hbar = (9/8) tau_RR e^2/hbar = {float(sp.Rational(5, 16) * sig):.4f} e^2/hbar "
        "(the value from the free-theory ratio C_J/C_T = 5/3 would be 0.2271)", ""]
check("(5/16)(9/10) C_T/C_T,free = (9/8) tau_RR", sp.simplify(sp.Rational(5, 16) * sig - sp.Rational(9, 8) * tau) == 0)
out.append("")

# ------------------------------------------------------------------ 5. Gross-Neveu-Yukawa at large N: 1/N and 1/N^2
# Fixed point of the three-loop chiral Ising RG functions as a double series in eps and u = 1/N_Zerf (N = 4 N_Zerf = 4/u).
u = sp.Symbol("u", positive=True)
K, U = 3, 4
y, lam = G.y, G.lam
by = (-eps * y + G.full("chiral Ising", "beta_y")).subs(G.N, 1 / u)
bl = (-eps * lam + G.full("chiral Ising", "beta_lam")).subs(G.N, 1 / u)
ser = lambda x: sp.series(sp.simplify(x), u, 0, U + 1).removeO()
s1 = sp.sqrt(9 + 4 * (33 + 1 / u) / u)
ys = [0, ser(1 / (3 + 2 / u))]
ls = [0, ser(sp.Rational(1, 72) * (3 - 2 / u + s1) / (3 + 2 / u))]
t = sp.Symbol("t")
for k in range(2, K + 1):
    yk, lk = sp.symbols("yk lk")
    Yt = sum(ys[i] * t**i for i in range(1, k)) + yk * t**k
    Lt = sum(ls[i] * t**i for i in range(1, k)) + lk * t**k
    e1 = sp.expand(by.subs({y: Yt, lam: Lt, G.eps: t})).coeff(t, k + 1)
    e2 = sp.expand(bl.subs({y: Yt, lam: Lt, G.eps: t})).coeff(t, k + 1)
    sol = sp.solve([e1, e2], [yk, lk], dict=True)[0]
    ys.append(ser(sol[yk]))
    ls.append(ser(sol[lk]))
Y2 = sum(ys[i] / 2 * eps**i for i in range(1, K + 1))          # our y*^2 = y_Zerf/2
L = sum(4 * ls[i] * eps**i for i in range(1, K + 1))            # our lambda_S = 4 lambda_Zerf
Nours = 4 / u
Yt_, _, cur = MODELS["chiral Ising"]
theory = lambda mult: dict(y=Yt_, lam=S_tensor(1), T=np.asarray(cur[0], complex), t=np.asarray(cur[1], float), mult=mult)


def correction(kind):
    tot = 0
    for name, c in load_coefficients(kind).items():
        ny, nl = degrees(name)
        if ny // 2 + nl > K:
            continue
        v1, v2 = _value(evaluate(name_net(name), theory(1.0))), _value(evaluate(name_net(name), theory(2.0)))
        if v1 == 0:
            continue
        p = sp.log(v2 / v1, 2)                                   # number of fermion traces: invariant scales as N^p
        assert p.is_integer, name
        tot += c * v1 * Nours**int(p) * Y2**(ny // 2) * L**nl
    return tot


def large_N(expr):
    e = sp.series(expr, eps, 0, K + 1).removeO()
    e = sum(sp.series(sp.expand(e.coeff(eps, k)), u, 0, 3).removeO() * eps**k for k in range(K + 1))
    return [sp.collect(sp.nsimplify(sp.expand(sp.expand(e).coeff(u, p) * 4**p)), eps) for p in (1, 2)]   # 1/N^p = (u/4)^p


CT1, CT2 = large_N((1 + (d - 1) / 2 * Nours + correction("T")) / ((d - 1) / 2 * Nours))
CJ1, CJ2 = large_N((Nours + correction("J")) / Nours)
z = sp.zeta(3)
out += ["## 5. Gross-Neveu-Yukawa model at large N", "",
        "C_T = C_T,ferm (1 + C_T1/N + C_T2/N^2 + ...), C_J = C_J,free (1 + C_J1/N + C_J2/N^2 + ...), with C_T,ferm the free-fermion part,",
        "as in Diab et al. (arXiv:1601.07198).", "",
        f"- C_T1 = {CT1}", f"- C_J1 = {CJ1}", f"- C_T2 = {CT2}", f"- C_J2 = {CJ2}", ""]
R = sp.Rational
check("C_T1 equals the exact large-N result of Diab et al. through eps^3",
      sp.simplify(CT1 - (R(2, 3) - R(11, 18) * eps - R(17, 54) * eps**2 + (z / 2 - R(365, 2592)) * eps**3)) == 0)
check("C_J1 equals the exact large-N result of Diab et al. through eps^3",
      sp.simplify(CJ1 - (-R(3, 2) * eps + R(1, 2) * eps**2 + R(15, 32) * eps**3)) == 0)
check("C_T2 = 5 eps - 307/72 eps^2 - (89/48 + 41 zeta3/12) eps^3",
      sp.simplify(CT2 - (5 * eps - R(307, 72) * eps**2 - (R(89, 48) + 41 * z / 12) * eps**3)) == 0)
check("C_J2 = 9 eps - 123/8 eps^2 + (9 zeta3/4 - 57/16) eps^3",
      sp.simplify(CJ2 - (9 * eps - R(123, 8) * eps**2 + (9 * z / 4 - R(57, 16)) * eps**3)) == 0)
out.append("")

open(os.path.join(ROOT, "results", "paper_tables.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
sys.exit(1 if failures else 0)
