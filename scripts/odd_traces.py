def as_class(r):
    return dict(name=r["name"], kind=r["kind"], ops=tuple(r["ops"]), ferm=tuple(tuple(f) for f in r["ferm"]),
                sig=tuple(tuple(tuple(e) for e in s) for s in r["sig"]), weight=Fraction(r["weight"]),
                nY=r["nY"], nQ=r["nQ"])


def loops(r):
    """the two fermion loops, each listed against the arrows starting at its operator (order of the spinor chain)"""
    pred = {b: a for a, b in (tuple(f) for f in r["ferm"])}
    ws = []
    for s in ("x", "0"):
        w, v = [s], pred[s]
        while v != s:
            w.append(v)
            v = pred[v]
        ws.append(w)
    return ws


def line_readings(r):
    """reading points (r1, r2) that start both traces at the two ends of the same scalar line, for the three lines.
    The chain is [operator, S, S, S, S]; rotation by j + 1 starts it just after the j-th Yukawa vertex of the loop."""
    wA, wB = loops(r)
    pos = {v: j + 1 for w in (wA, wB) for j, v in enumerate(w) if j}
    res = []
    for a, b in r["sig"]:
        va, vb = (a[0], b[0]) if a[0] in wA else (b[0], a[0])
        res.append((pos[va], pos[vb]))
    return res


