#!/usr/bin/env python3
"""Odd fermion-loop contributions to <TT> and <JJ> at four loops (see ODD_LOOPS.md).

For three-dimensional theories without a four-dimensional counterpart (e.g. an odd number of two-component Majorana
fermions), fermion loops with an odd number of Yukawa vertices need not vanish if the gamma algebra keeps
Tr(g g g) ~ eps^{mu nu rho}.  We use the semi-naive DREG_3 prescription of Zerf et al. (arXiv:1709.05057):
    Tr(g_a g_b g_c) = i eps~_abc tr1,   eps~ eps~ = det of D-dimensional deltas,  even traces unchanged,
with longer odd traces reduced by the Clifford product expansion (coefficient of Gamma^(3)).
The first contributions to <TT> and <JJ> are four-loop classes with two fermion loops, each carrying the operator
(Tpsi or Jpsi) and three Yukawa vertices; every other class with an odd loop vanishes after integration.

Outcome (details in the output; section 6 tests the sewn-trace formulation): the five-gamma odd trace is not cyclic for D != 3, so the result depends on where
each trace is read ("reading point"), by terms that are O(1) at D = 4.  For <JJ> the double poles come from reading
the trace at the current, which breaks the Ward identity; they are absent for every other reading point.  The
coefficient of the simple pole, and hence the O(eps^3) term of C_T and C_J, depends on the reading point for both
correlators, so the script reports the values for each choice instead of a single correction.
N=1 supersymmetry selects one of them for <TT>: the supercurrent <S Sbar> has no odd loops through O(eps^3), and
C_S/C_S,free = C_T/C_T,free fixes kappa_T = 7/6 - zeta3, the same-line rule (ODD_LOOPS.md); section 3.2 checks
that the same-line value computed here equals ctcj.formulas4.KAPPA_T_ODD, which C_T at 3d-only points now includes.

    python3 scripts/odd_traces.py              # from the cached integrals (~5 min)
    python3 scripts/odd_traces.py --integrals  # recompute the 12 integrals read at the operator (minutes, 4 processes)
    python3 scripts/odd_traces.py --depth4     # recompute the six <TT> classes at Forcer depth 4 (1-3 min each)
    python3 scripts/odd_traces.py --reading    # recompute all 25 pairs of reading points, the three-loop vertex
                                               # and the Pauli-algebra variant (about 1.5 h with 4 processes)
    python3 scripts/odd_traces.py --sewing     # recompute the two sewings of section 6 (about 1.5 h with 4 processes)

Writes results/odd_traces.md.  Exit code non-zero if a check that should pass fails."""
