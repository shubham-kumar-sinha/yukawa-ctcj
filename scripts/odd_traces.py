def flavour(r, y, T):
    ws = loops(r)
    lab = {}
    for k, (a, b) in enumerate(r["sig"]):
        lab[a[0]] = k; lab[b[0]] = k
    words = [["T" if v in ("x", "0") else lab[v] for v in w] for w in ws]
    tot = 0
    for a in itertools.product(range(y.shape[0]), repeat=3):
        f = 1
        for w in words:
            M = np.eye(y.shape[1], dtype=complex)
            for e in w:
                M = M @ (T if e == "T" else y[a[e]])
            f *= np.trace(M)
        tot += f
    return tot


def majorana_u1(qf, qs, n0f, n0s, rng):
    """random theory of real symmetric Yukawa matrices (Majorana basis) with an exact U(1)"""
    def blk(q):
        A = np.zeros((2 * len(q),) * 2)
        for j, c in enumerate(q):
            A[2 * j:2 * j + 2, 2 * j:2 * j + 2] = c * np.array([[0, -1], [1, 0]])
        return A
    A = np.zeros((2 * len(qf) + n0f,) * 2); A[:2 * len(qf), :2 * len(qf)] = blk(qf)
    t = np.zeros((2 * len(qs) + n0s,) * 2); t[:2 * len(qs), :2 * len(qs)] = blk(qs)
    K = 4 * max(list(qf) + list(qs)) + 3
    y0 = rng.normal(size=(len(t), len(A), len(A))); y0 = y0 + y0.transpose(0, 2, 1)
    y = sum(np.einsum("ba,ji,bjk,kl->ail", expm(2 * np.pi * k / K * t), expm(2 * np.pi * k / K * A), y0,
                      expm(2 * np.pi * k / K * A)) for k in range(K)) / K
    Th = -1j * A
    lhs = 1j * (np.einsum("aij,jk->aik", y, Th) - np.einsum("ij,ajk->aik", Th, y))
    rhs = np.einsum("ab,bij->aij", t, y)
    return y, Th, (np.allclose(lhs, rhs) or np.allclose(lhs, -rhs))


