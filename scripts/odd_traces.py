def tr5(vecs, E, r=0, form=odd_trace):
    """Tr(v1slash ... v5slash)/(i tr1) read from position r, with the three-form E in place of eps~"""
    names = [f"e{k}" for k in range(5)]
    val = dict(zip(names, vecs))
    tot = 0
    for s, ds, abc in form(names[r:] + names[:r]):
        f = s
        for d in ds:
            a, b = d.split(".")
            f = f * (val[a] @ val[b])
        tot = tot + f * np.einsum("ijk,i,j,k", E, val[abc[0]], val[abc[1]], val[abc[2]])
    return tot


