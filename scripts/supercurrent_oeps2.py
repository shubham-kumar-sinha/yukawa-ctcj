#!/usr/bin/env python3
"""C_S/C_S,free from <S Sbar> through three loops at N=1 fixed
points, compared with C_T/C_T,free (ctcj.theory.Theory.CT).

    python3 scripts/supercurrent_compute.py --w 0 2 4 --proj P     (integrals; ~1 min, cached)
    python3 scripts/supercurrent_compute.py --w 2 4 --proj W1 W2 W3 --ward    (Ward checks; ~3 min, cached)
    python3 scripts/supercurrent_oeps2.py                         (~1 min; writes results/supercurrent_eps2.md)

Only D-D classes contribute to the projection (S_W = gamma_mu psi is annihilated by P); classes with a cut vertex
are dropped (their x- or 0-side blob is a function of Q only, i.e. gamma_mu(...) or Q_mu(...), also annihilated).
Renormalisation: y0 = mu^ep (y + beta1(y)/eps), eps = 2 ep, inserted into the two-loop term (as ctcj/assemble.py);
lambda first needs a counterterm at the next order.  Flavour factors are evaluated for each theory
(y^a_bc = h_abc, Tr 1 = 1 per Majorana).  At a fixed point y* = sqrt(eps)(a + eps b), lambda* = eps c:
    C_S/C_S,free = 1 + eps H2(a) r2_0/N + eps^2 [2 Tr(ab) r2_0 + H2(a) r2_1/2 + ren3_0(a, c)]/N
with r2 = (two-loop position ratio)/H2 = r2_0 + r2_1 ep, ep = eps/2.
"""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np
import sympy as sp
from ctcj import epsseries as S
from ctcj.assemble import position_ratio
from ctcj.supercurrent import generate_S, flavour
from ctcj.theory import Theory
from ctcj import betasJ as BJ

ROOT = os.path.join(os.path.dirname(__file__), "..")
e = S.EP
cache = json.load(open(os.path.join(ROOT, "data", "supercurrent_classes.json")))
SYM = {"ep": e, **{f"z{k}": sp.Symbol(f"z{k}") for k in range(2, 8)}}
NUM = {S.ELL: 0.3, S.GAMMA_E: 0.5772156649015329, S.LOGPI: np.log(np.pi), S.LOG4: np.log(4.0),
       **{sp.Symbol(f"z{k}"): float(sp.zeta(k)) for k in range(2, 8)}}


def X(c):
    return sp.sympify(cache[f"{c['name']}|P"]["X"], locals=SYM)


FREE = generate_S(0, 0)[0]
XF = X(FREE)
C2 = generate_S(2, 0)
C3 = generate_S(4, 0) + generate_S(2, 1) + generate_S(0, 2)


def susy_lambda(h):
    return np.einsum("abe,cde->abcd", h, h) + np.einsum("ace,bde->abcd", h, h) + np.einsum("ade,bce->abcd", h, h)


def pieces(h, lam):
    """r2 (series, per unit H2), ren3 (series, three-loop + counterterm) for couplings h, lam; per unit N."""
    n = h.shape[0]
    H2 = float(np.einsum("abc,abc->", h, h))
    f2 = [flavour(c, h) / H2 for c in C2]
    for c, f in zip(C2, f2):
        assert abs(f - 1) < 1e-9, (c["name"], f)
    r2 = position_ratio("S", 2, sp.expand(sum(X(c) for c in C2)), XF)
    X3 = sp.expand(sum(sp.Float(flavour(c, h, lam), 15) * X(c) for c in C3))
    R3 = position_ratio("S", 3, X3, XF)
    y = h.astype(complex)
    b1 = BJ.beta1_y(y, 1.0)
    ins = float(2 * sum(np.trace(y[a] @ b1[a]) for a in range(n)).real)
    ren3 = S.trunc(sp.expand(R3 + ins * r2 / (2 * e)))
    return H2, r2, ren3


def num(x):
    return complex(sp.N(sp.expand(x).subs(NUM)))


OUT = ["# The N=1 supercurrent through O(eps^2): conservation and C_S = C_T", "",
       "Generated by `scripts/supercurrent_oeps2.py` from the integrals cached in `data/supercurrent_classes.json`; see",
       "ODD_LOOPS.md.  Paper: section 5.4 and appendix F.", ""]


def say(line=""):
    print(line, flush=True)
    OUT.append(line)


def flag(ok):
    return "yes" if ok else "**NO**"


# ------------------------------------------------------------------ 1. poles cancel for any h (SUSY quartic)
rng = np.random.default_rng(5)
say("## Pole cancellation after coupling renormalization (three loops)")
say("")
say("| couplings | poles of C_S/C_S,free cancel |")
say("|---|---|")
ok_poles = True
for n in (1, 2, 3):
    h = rng.normal(size=(n, n, n))
    h = sum(np.transpose(h, p) for p in [(0, 1, 2), (0, 2, 1), (1, 0, 2), (1, 2, 0), (2, 0, 1), (2, 1, 0)]) / 6
    H2, r2, ren3 = pieces(h, susy_lambda(h))
    p = [abs(num(ren3.coeff(e, k))) for k in (-3, -2, -1)]
    ok = max(p) < 1e-9 * (1 + abs(num(ren3.coeff(e, 0))))
    ok_poles &= ok
    say(f"| random totally symmetric h_abc, {n} superfield(s), lambda = hh + 2 pairings | {flag(ok)} |")
h = rng.normal(size=(2, 2, 2))
h = sum(np.transpose(h, p) for p in [(0, 1, 2), (0, 2, 1), (1, 0, 2), (1, 2, 0), (2, 0, 1), (2, 1, 0)]) / 6
H2, r2, ren3 = pieces(h, susy_lambda(h) * 1.7)
ctrl = abs(num(ren3.coeff(e, -1)))
ok_ctrl = ctrl > 1e-3
say(f"| control: lambda = 1.7 x supersymmetric value | no, as expected (1/ep coefficient {ctrl:.3f}) |")
say("")

# ------------------------------------------------------------------ 2. fixed points
exec(open(os.path.join(ROOT, "scripts", "liendo_rong.py")).read().split("MODELS = [")[0])   # potts, o3_traceless
MODELS = [("N=1 super-Ising", ([np.ones((1, 1, 1))], [np.ones((1, 1, 1, 1))], None), 1 / 14),
          ("super-Potts S3 (N=2)", potts(3), 1 / 6), ("super-Potts S4", potts(4), 1 / 10),
          ("super-Potts S5", potts(5), 3 / 34), ("O(3)/Z2", o3_traceless(), 7 / 30)]
say("## C_S/C_S,free = C_T/C_T,free = 1 + c1 eps + c2 eps^2 at the N=1 fixed points")
say("")
say("| fixed point | c1 (S) | c1 (T) | c2 (S) | c2 (T) | equal, no logs |")
say("|---|---|---|---|---|---|")
ok_fp = True
for name, (Ys, Ls, _), gref in MODELS:
    th = Theory(Y=[np.array(y, complex) for y in Ys], L=Ls, mult=1.0, name=name)
    best = None
    for fp in th.fixed_points(starts=80):
        h = th.y_of(fp["a"]).real
        if np.abs(h).max() < 1e-6:
            continue
        gam = 0.5 * np.einsum("aij,bji->ab", h, h)
        if not np.allclose(gam, gam[0, 0] * np.eye(len(gam)), atol=1e-8) or abs(gam[0, 0] - gref) > 1e-6:
            continue
        if np.abs(th.lam_of(fp["c"]) - susy_lambda(h)).max() < 1e-7:
            best = fp
            break
    assert best is not None, name
    a, b, lam = th.y_of(best["a"]).real, th.y_of(best["b"]).real, th.lam_of(best["c"])
    sym = max(np.abs(a - np.transpose(a, p)).max() for p in [(1, 0, 2), (2, 1, 0)])
    assert sym < 1e-9, f"{name}: h not totally symmetric in this basis ({sym})"
    N = a.shape[0]
    H2, r2, ren3 = pieces(a, lam)
    trab = float(np.einsum("abc,abc->", a, b))
    c1 = sp.expand(H2 * r2.coeff(e, 0) / N)
    c2 = sp.expand((2 * trab * r2.coeff(e, 0) + H2 * r2.coeff(e, 1) / 2 + ren3.coeff(e, 0)) / N)
    resid = max(abs(num(sp.diff(c2, s))) for s in (S.ELL, S.GAMMA_E, S.LOGPI)) + abs(num(sp.diff(c1, S.ELL)))
    c1n, c2n = num(c1.subs(S.ELL, 0)).real, num(c2.subs(S.ELL, 0)).real
    t1, t2 = th.CT(best)
    ok = resid < 1e-9 and abs(c1n - t1) < 1e-9 and abs(c2n - t2) < 1e-9
    ok_fp &= ok
    say(f"| {name} | {c1n:+.8f} | {t1:+.8f} | {c2n:+.8f} | {t2:+.8f} | {flag(ok)} |")
say("")

# ------------------------------------------------------------------ 3. Ward identities in momentum space
# Q_mu G_{mu nu} = 0 = G_{mu nu} Q_nu for the bare correlator, order by order in h (massless dim reg: no contact
# terms).  All operator types (D, W) and all non-scaleless classes, including those with a cut vertex.
# Integrals: python3 scripts/supercurrent_compute.py --w 2 4 --proj W1 W2 W3 --ward
say("## Ward identities Q_mu G_{mu nu} = G_{mu nu} Q_nu = 0 (bare correlator, random symmetric h, supersymmetric quartic)")
say("")
say("W1 = Tr[Q_mu G_{mu nu} gamma_nu], W2 = Tr[Q_mu G_{mu nu} Q_nu Qslash], W3 = Tr[G_{mu nu} Q_nu gamma_mu]; all operator types")
say("(D and W ends) and all classes without a scaleless subgraph, including those with a cut vertex.")
say("")
say("| loops | contraction | classes (non-zero) | sum vanishes (relative 1e-10) |")
say("|---|---|---|---|")
ok_ward = True
h = rng.normal(size=(3, 3, 3))
h = sum(np.transpose(h, p) for p in [(0, 1, 2), (0, 2, 1), (1, 0, 2), (1, 2, 0), (2, 0, 1), (2, 1, 0)]) / 6
lam = susy_lambda(h)
for w in (2, 4):
    cls = []
    for ops in [("D", "D"), ("W", "D"), ("D", "W"), ("W", "W")]:
        nW = ops.count("W")
        for nQ in range(0, (w - nW) // 2 + 1):
            if w - nW - 2 * nQ >= 0:
                cls += generate_S(w - nW - 2 * nQ, nQ, ops, "not_scaleless")
    fl = [flavour(c, h, lam) for c in cls]
    for proj in ("W1", "W2", "W3"):
        xs = [sp.sympify(cache[f"{c['name']}|{proj}"]["X"], locals=SYM) for c in cls]
        tot = sp.expand(sum(sp.Float(f, 15) * x for f, x in zip(fl, xs)))
        scale = max(abs(num(x.coeff(e, k))) * abs(f) for x, f in zip(xs, fl) for k in range(-3, 2)) or 1
        res = max(abs(num(tot.coeff(e, k))) for k in range(-3, 2))
        nz = sum(1 for x in xs if x != 0)
        ok = res < 1e-10 * scale
        ok_ward &= ok
        say(f"| {2 if w == 2 else 3} | {proj} | {len(cls)} ({nz}) | {flag(ok)} |")
say("")
ok_all = ok_ward and ok_poles and ok_ctrl and ok_fp
say(f"Ward identities (two and three loops): {'PASS' if ok_ward else 'FAIL'}.  Poles cancel for the supersymmetric quartic only: "
    f"{'PASS' if ok_poles and ok_ctrl else 'FAIL'}.  C_S = C_T through O(eps^2), no logs: {'PASS' if ok_fp else 'FAIL'}.")
open(os.path.join(ROOT, "results", "supercurrent_eps2.md"), "w").write("\n".join(OUT) + "\n")
sys.exit(0 if ok_all else 1)
